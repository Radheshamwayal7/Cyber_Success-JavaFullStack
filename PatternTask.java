public class PatternTask {
    public static void main(String[] args) {
        
        char ch = 'a';
        for(int i = 4; i >= 1; i--) {
            for(int j = 1; j <= i; j++) {
                System.out.print(ch + " ");
            
            }
        System.out.println();
        }
    }
}
